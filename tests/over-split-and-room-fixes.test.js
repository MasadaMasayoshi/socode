'use strict';
// 利用者からの修正依頼（患者36_修正依頼_5件.txt）：「分割されすぎているし。二つ目のやつは不必要でいい」。
//  ・「疼痛:」の下の「安静時ペインスケール「2-3」」「体位変換時「5-6」…」「「動かなかったら痛くないよ」」が
//    3枚のカードに分かれていた → 見出しごと1枚にまとめる。
//  ・「「先生にお任せするしかない」」（発言だけの行）が、直前の患者の発言のカードから切り離されていた → 直前に続ける。
//  ・「帰室(個室301号室)」（部屋の移動・部屋番号だけ）がOデータになっていた → 不要な情報にする。

const test = require('node:test');
const assert = require('node:assert/strict');
const { loadApp } = require('./app-helpers');

const { groupClinicalPhrasesWithTimestamps, isUnnecessaryBoilerplateText } = loadApp();
const cards = text => Array.from(groupClinicalPhrasesWithTimestamps(text.normalize('NFKC')))
  .filter(i => !i.isUnnecessaryBoilerplate).map(i => i.text);

test('値の無い見出し「疼痛:」の下の短い行は、見出しごと1枚のカードにまとまる（利用者からの修正依頼）', () => {
  const out = cards(['12:00 帰室', '疼痛:', '安静時ペインスケール「2-3」', '体位変換時「5-6」（一時的なため鎮痛剤使用なし）', '「動かなかったら痛くないよ」'].join('\n'));
  // 見出しの下の行は1つにまとめたうえで、患者の発言（S）と観察（O）は同じ場面の2枚に分ける（患者36の指摘）
  // 発言（S）には、何の場面の発言か分かるよう同じ文の観察を（場面：…）として添える（「分けると何について言及しているのか分かりにくい」）
  const pain = out.filter(t => t.includes('疼痛'));
  assert.equal(pain[0], '疼痛: 安静時ペインスケール「2-3」、体位変換時「5-6」(一時的なため鎮痛剤使用なし)');
  assert.match(pain[1], /^疼痛: 「動かなかったら痛くないよ」（場面：安静時ペインスケール「2-3」/);
});

test('見出しの下が1行だけなら、これまで通り見出しが前置きされた1枚のカード（回帰確認）', () => {
  assert.deepEqual(cards(['疼痛:', '安静時ペインスケール「2-3」'].join('\n')), ['疼痛: 安静時ペインスケール「2-3」']);
});

test('見出しの下が自前のラベルを持つ行（「血液型: A型」等）なら、まとめずに別々のカードのまま（誤結合の防止）', () => {
  const out = cards(['身体的状態:', '血液型: A型', '視覚障害: 眼鏡使用'].join('\n'));
  assert.ok(out.some(t => t === '血液型: A型'));
  assert.ok(out.some(t => t === '視覚障害: 眼鏡使用'));
});

test('60文字を超える長い文章が続く場合は、まとめずに別々のカードのまま（誤結合の防止）', () => {
  const long1 = '入院後、キルシュナー牽引4kgを実施し、足背動脈の触知は良好で左右差はなく、知覚異常や冷感も認めなかったため経過観察とした。';
  const long2 = '動かなければ疼痛の訴えはなく、鎮痛剤の内服も行わずに経過しており、夜間も比較的良眠できている様子が観察されている状態である。';
  const out = cards(['経過:', long1, long2].join('\n'));
  assert.equal(out.length, 2);
});

test('発言だけの行は、直前の同じ日時の患者の発言のカードの続きになる（利用者からの修正依頼）', () => {
  const out = cards(['入院時', '今回の受傷について：息子たちの前では「大丈夫よ」と気丈な言動あり。「孫に会いたい」と前向き。', '「先生にお任せするしかない」'].join('\n'));
  // 発言どうしは1枚にまとめたうえで、観察（気丈な言動あり・前向き）とは同じ場面の別のカードに分ける（患者36の指摘）
  assert.deepEqual(out, ['今回の受傷について: 息子たちの前では、気丈な言動あり。前向き。', '今回の受傷について: 「大丈夫よ」（場面：息子たちの前では、気丈な言動あり）「孫に会いたい」（場面：前向き）「先生にお任せするしかない」']);
});

test('直前のカードが患者の発言を含まない観察所見なら、発言だけの行は別のカードのまま（誤結合の防止）', () => {
  const out = cards(['精神状態は現実認識できている。', '「先生にお任せするしかない」'].join('\n'));
  assert.equal(out.length, 2);
});

test('部屋の移動・部屋番号だけの行は不要な情報、所見を含む行は対象外（利用者からの修正依頼）', () => {
  assert.equal(isUnnecessaryBoilerplateText('帰室(個室301号室)'), true);
  assert.equal(isUnnecessaryBoilerplateText('301号室へ転室'), true);
  assert.equal(isUnnecessaryBoilerplateText('帰室時、顔色不良'), false);
  assert.equal(isUnnecessaryBoilerplateText('入室'), false, '部屋番号の無い「入室」（手術室入室等）は対象外');
});

test('「・」が長い文の途中で2つの語をつないでいるだけなら分けない（利用者からの修正依頼：患者34）', () => {
  const out = cards('14:00 RH PTによるリハビリ開始 車いすに移乗し、リハビリ室に移動 立位保持・歩行訓練、関節可動域訓練やマッサージ行う ペインスケール「5」まで上昇したが、帰室後「2」となっているため追加の薬剤希望なし');
  assert.equal(out.length, 1);
  assert.match(out[0], /立位保持・歩行訓練/);
  assert.deepEqual(cards('シャワー浴・弾性ストッキング着用を実施'), ['シャワー浴', '弾性ストッキング着用を実施'], '短い語句の列挙はこれまで通り分ける');
});

test('コロンの無い見出し語（術後肢位・病室環境等）の下の行は、見出しごと1枚にまとめる（利用者からの修正依頼：患者37「細かくなりすぎている」）', () => {
  const out = cards(['術後肢位', '股関節90度以上の屈曲禁止', '軽度外転位で、内旋位は禁止', '側臥位時は外転枕使用すること', '両下肢のあいだに外転枕を挟んでいる', '21時', '血圧100〜110/80〜70mmHg'].join('\n'));
  // 「術後肢位」の「術後」は日時として剥がさず、見出しのまま残す（時系列の整理の修正：患者36）
  assert.ok(out.includes('術後肢位: 股関節90度以上の屈曲禁止、軽度外転位で、内旋位は禁止、側臥位時は外転枕使用すること、両下肢のあいだに外転枕を挟んでいる'), out.join(' / '));
  assert.ok(out.includes('血圧100〜110/80〜70mmHg'), '時刻が変わった後のカードには見出しを付けない');
  // 「回診」のような出来事の語は見出しとして扱わない（下に別々の観察が続くため）
  const r = cards(['8:00 回診', '酸素OFF、硬膜外麻酔抜去、フットポンプOFF', '創部 ガーゼ汚染なし、SBチューブ挿入中', '膀胱留置カテーテル留置中'].join('\n'));
  assert.ok(r.length >= 3, r.join(' / '));
});

test('医師の説明の行と、その続きの方針・目標の行は1枚にまとめ、医師の言葉の「」はSにしない（利用者からの修正依頼：患者37）', () => {
  const src = ['8:00 回診', '膀胱留置カテーテル留置中', '本人へ主治医より「経過良好」と説明あり、本日から離床開始許可あり', 'リハビリテーションスケジュールに沿って開始する。', '退院目標：杖歩行で自宅退院', 'リハビリテーションスケジュール：術後1日目から開始'].join('\n');
  const all = Array.from(loadApp().classifyTextByRules(src));
  const card = all.find(c => c.text.startsWith('本人へ主治医より'));
  assert.equal(card.text, '本人へ主治医より「経過良好」と説明あり、本日から離床開始許可あり。リハビリテーションスケジュールに沿って開始する。退院目標:杖歩行で自宅退院');
  assert.equal(card.type, 'o', '医師の言葉の「」は患者の発言ではない');
  assert.ok(all.some(c => c.text === 'リハビリテーションスケジュール:術後1日目から開始'), '方針・予定の語が無い行はつなげない');
  assert.ok(all.some(c => c.text.includes('膀胱留置カテーテル留置中') && !c.text.includes('主治医')), '説明より前の行は説明のカードに入れない');
  const s = Array.from(loadApp().classifyTextByRules('「痛み止めって我慢できなくなってから使うものでしょう？」'));
  assert.equal(s[0].type, 's', '患者本人の発言は引き続きS');
});

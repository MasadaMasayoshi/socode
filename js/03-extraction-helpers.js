    // 内容が見出し語だけで実質的な情報が無かった）。見出し語のみの文字列には値が無く、
    // カード化しても意味が無いため、他の空文字判定と同様にここで除外する。
    // FIELD_LABELSに登録済みの見出し語すべてに加え、性別は上で登録したため既に含まれるが、
    // 将来見出し語registryが変わっても対応できるよう明示的にSetを組み立てる。
    const BARE_FIELD_HEADER_WORDS = new Set(FIELD_LABELS.map(f => f.key));
    function isBareFieldHeaderOnly(str) {
      const trimmed = normalizeFieldLabelHeadingWord((str || '').replace(/[:：]\s*$/, '').trim());
      return BARE_FIELD_HEADER_WORDS.has(trimmed);
    }

    // 「【保険】」「【既往歴】」のように、見出しラベル（FIELD_LABELS）だけが独立した行になって
    // おり、実際の値は次の行に別に書かれている記録形式がある（例：「【保険】\n社会保険」）。
    // この場合、見出し行自体は値を持たないため、これまでは他の内容を持たない括弧書き見出し
    // （「【身長・体重】」等）と同様にそのまま破棄され、直後の値の行（「社会保険」等）が見出しの
    // 文脈を失ったまま無関係な一般カードとして抽出され、見出しラベルに応じたタグ
    // （FIELD_LABEL_DEFAULT_TAGS等）も付与されなくなっていた（利用者からのアップロード文書・
    // スクリーンショットで発覚：「社会保険」がタグ未設定になっていた）。
    // 見出し行を検出した場合、次の行にこの見出しラベルを引き継ぎ、直後の1行だけをその見出し
    // 付きカードとして扱う（呼び出し側のpendingFieldLabelKeys参照）。
    //
    // OCRの影響で閉じ括弧が半角の「)」や全角の「）」など開き括弧と不揃いになっている場合
    // （例:「【診断）」）や、逆に開き括弧が失われ複数の見出し語が「・」でつながれたまま行末に
    // 残骸の閉じ括弧だけが残っている場合（例:「氏名・年齢・性別・】」）にも対応する。
    // 「診断」→「診断名」、「家族構成」→「家族関係」の別名対応表（FIELD_LABEL_HEADING_ALIASES・
    // normalizeFieldLabelHeadingWord）は、FIELD_LABELS定義の直後（見出し検出の正規表現を
    // 組み立てるより前）で共通定義済みのため、ここではそれをそのまま使う。
    function detectFieldLabelHeadingOnlyLine(rawLine) {
      const trimmed = (rawLine || '').trim();
      if (!trimmed) return null;
      // 単一の見出し語が括弧（開き・閉じの不一致含む）で囲まれているだけの行
      const bracketed = trimmed.match(/^[【\[]\s*([^\d:：()（）\[\]【】]{1,12})\s*[\]】)）]?\s*$/);
      if (bracketed) {
        const key = normalizeFieldLabelHeadingWord(bracketed[1].trim());
        return BARE_FIELD_HEADER_WORDS.has(key) ? [key] : null;
      }
      // 複数の見出し語が「・」でつながれ、末尾に括弧の残骸だけが残っている行
      if (trimmed.includes('・')) {
        const rawTokens = trimmed.split('・').map(t => t.trim());
        const isJunkToken = t => t.length === 0 || /^[\[【\]】]+$/.test(t);
        const labelTokens = rawTokens.filter(t => !isJunkToken(t)).map(normalizeFieldLabelHeadingWord);
        if (labelTokens.length >= 2 && labelTokens.every(t => BARE_FIELD_HEADER_WORDS.has(t))) {
          return labelTokens;
        }
      }
      return null;
    }


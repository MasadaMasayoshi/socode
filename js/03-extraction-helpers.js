    // 「氏名　年齢　性別」のような表形式の見出し行で、対応する値が見つからない（AIが値を
    // 見つけられず見出し語自体をtextとして返してしまう等の）場合、見出し語だけが本文として
    // 残ってしまい、「氏名」「年齢」「性別」としか表示されず何の情報にもならないカードが

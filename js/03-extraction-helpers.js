    // ------------------------------------------------------------------------
    // 「入院」「実習」「術前」「術中」「術後」「◯日目」「検査データ」等の語を含むテキスト
    // （マーカーとして剥がされたタイムスタンプ文字列、または「＜実習1日目…＞」のような
    // 見出し行そのもの）から、以降を「入院後」として記憶すべきかどうかを判定する。
    // 「入院前」は明示的な巻き戻し（既往歴・生活歴等を扱う冒頭部分に戻ったことを示す
    // 強い手がかり）として、他のどの語より優先して「入院前」を返す。
    // 該当する手がかりが無ければnullを返し、呼び出し側は現在の状態を変えない。
    // ==========================================================================
    // 日付（術後日数）付きの日時（groupClinicalPhrasesWithTimestampsのapplyTimeMarker参照）
    // ------------------------------------------------------------------------
    // 「術後 1 日目」→「術後1日目」、「手術翌日」→「術後1日目」のように、日の区切りの書き方をそろえる
    function normalizeDayLabel(raw) {
      const t = (raw || '').replace(/\s+/g, '');
      if (t === '手術翌日') return '術後1日目';
      return t;
    }
    // 次の日の呼び方（手術当日→術後1日目→術後2日目…、入院2日目→入院3日目、6月10日→6月11日）。分からなければnull
    function nextDayLabel(label) {
      const t = normalizeDayLabel(label);
      let m;
      if (t === '手術当日') return '術後1日目';
      if (t === '手術前日') return '手術当日';
      if (t === '入院当日') return '入院2日目';
      if ((m = t.match(/^術後(\d+)日目$/))) return `術後${Number(m[1]) + 1}日目`;
      if ((m = t.match(/^入院(\d+)日目$/))) return `入院${Number(m[1]) + 1}日目`;
      if ((m = t.match(/^産褥(\d+)日目$/))) return `産褥${Number(m[1]) + 1}日目`;
      if (t === '入院前日') return '手術当日';
      if ((m = t.match(/^(\d+)日目$/))) return `${Number(m[1]) + 1}日目`;
      if ((m = t.match(/^(?:(\d{1,4})年)?(\d{1,2})月(\d{1,2})日/))) {
        const year = m[1] ? Number(m[1]) : 2001; // 年が無いときはうるう年でない年で計算する
        const d = new Date(year, Number(m[2]) - 1, Number(m[3]) + 1);
        return `${m[1] ? `${d.getFullYear()}年` : ''}${d.getMonth() + 1}月${d.getDate()}日`;
      }
      return null;
    }
    // 見出しの中から日の手がかりを取り出す。手術からの日数の書き方を入院からの日数より優先する
    // （「＜実習3日目（入院3日目、手術当日・術直後）＞」→手術当日、「＜実習1日目(入院1日目、手術前々日)＞」→入院1日目）
    function extractDayLabelFromHeading(text) {
      const t = (text || '').normalize('NFKC');
      const m = t.match(/術後\s*\d+\s*日目/) || t.match(/手術当日|手術翌日|手術前日/) || t.match(/入院\s*\d+\s*日目|入院当日/) ||
        t.match(/術前|入院時/); // 「＜術前検査結果＞」のように日数は無いが時期の分かる見出し
      return m ? normalizeDayLabel(m[0]) : null;
    }
    // 日時から日の部分だけを取り出す（「術後1日目 12:00」→「術後1日目」、「12:00」→''、「日時不明」→''）。
    // 総合アセスメント表の「入院後」欄で、日ごとの見出しを付けるために使う。
    function timestampDayPart(ts) {
      const t = (ts || '').trim();
      if (!t || t === '日時不明') return '';
      const m = t.match(/^(.*?)\s*\d{1,2}:\d{2}$/);
      return m ? m[1].trim() : t;
    }
    // 日時から時刻の部分だけを取り出す（「術後1日目 12:00」→「12:00」。時刻が無ければ''）
    function timestampClockPart(ts) {
      const m = (ts || '').trim().match(/(\d{1,2}:\d{2})$/);
      return m ? m[1] : '';
    }
    // 日の時系列の順番（小さいほど前）。分からない日はnull。
    function dayRank(day) {
      const t = normalizeDayLabel(day);
      let m;
      if (!t) return null;
      if (t === '入院前') return 0;
      if (t === '入院時' || t === '入院当日') return 10;
      if ((m = t.match(/^入院(\d+)日目$/))) return 10 + Number(m[1]) - 1;
      if (t === '術前') return 30;
      if (t === '手術前々日') return 38;
      if (t === '手術前日') return 39;
      if (t === '手術当日') return 40;
      if (t === '術中') return 40.5;
      if (t === '入院前日') return 39;
      if ((m = t.match(/^産褥(\d+)日目$/))) return 60 + Number(m[1]);
      if (t === '術後') return 41;
      if ((m = t.match(/^術後(\d+)日目$/))) return 41 + Number(m[1]);
      if ((m = t.match(/^(?:(\d{1,4})年)?(\d{1,2})月(\d{1,2})日$/))) return 100000 + (Number(m[1] || 0) * 400) + Number(m[2]) * 32 + Number(m[3]);
      return null;
    }
    // カードを日（timestampDayPart）ごとにまとめ、日の順番（dayRank）で並べる。日の分からないカード（時刻だけ等）は
    // 直前のカードと同じ日に入れる。同じ日の中は元の順番のまま（利用者が上下移動で入れ替えた順）。
    // 順番の分からない日の区切りは、最初に出てきた位置のままにする。
    // 例：検査データの表は「入院時」「術後1日目」の値が交互に並ぶが、入院時・術後1日目ごとにまとめる。
    function groupItemsByDay(list) {
      const order = [];
      const byDay = new Map();
      let prevDay = '';
      (list || []).forEach(item => {
        const day = timestampDayPart(item.timestamp) || prevDay;
        prevDay = day;
        if (!byDay.has(day)) { byDay.set(day, []); order.push(day); }
        byDay.get(day).push(item);
      });
      const knownSlots = order.map((d, i) => (dayRank(d) !== null ? i : -1)).filter(i => i >= 0);
      const knownSorted = knownSlots.map(i => order[i]).sort((a, b) => dayRank(a) - dayRank(b));
      knownSlots.forEach((slot, k) => { order[slot] = knownSorted[k]; });
      return order.map(day => ({ day, items: byDay.get(day) }));
    }

    // 総合アセスメント表の欄の中を日ごとに見出しで区切るか（入院前・入院後の欄だけ）。区切りが1つだけで、
    // それが欄の名前と同じ「入院前」なら見出しは付けない。
    // どの欄も日の順番に並べるが、小見出しを付けるのは入院前・入院後の欄だけ。
    function assessmentDayGroups(col, list) {
      // 診断名・現病歴などの背景情報は、欄の一番上に「背景」としてまとめ、観察・ケアの記録（主な情報）と分ける
      const background = (list || []).filter(isAssessmentBackgroundItem);
      const bgGroup = background.length ? [{ day: ASSESSMENT_BACKGROUND_LABEL, items: background, background: true }] : [];
      const groups = groupItemsByDay((list || []).filter(i => !isAssessmentBackgroundItem(i)));
      if (groups.length === 0) return bgGroup;
      // 背景のまとまりがあるときは、その下の観察・ケアの記録にも見出しを付けて境目を分かりやすくする
      const flat = () => [...bgGroup, { day: bgGroup.length ? '観察・ケアの記録' : '', items: groups.flatMap(g => g.items) }];
      if (col !== 'preadmission' && col !== 'postadmission') return flat();
      if (groups.length === 1 && (groups[0].day === '' || groups[0].day === '入院前')) return flat();
      return [...bgGroup, ...groups];
    }
    // 【背景情報】利用者からの指摘（患者36・4.姿勢の欄）：「診断名などは背景情報として置くなら可ですが、主タグには
    // しなくてよい」。診断名・病名・現病歴・既往歴・手術術式・主訴などの見出しのカードと、「〜と診断され」の文は、
    // どの欲求の欄でも観察・ケアの記録とは分けて「背景」として一番上にまとめる（タグはそのまま。書き出しも同じ）。
    const ASSESSMENT_BACKGROUND_LABEL = '背景（診断名・現病歴など）';
    const ASSESSMENT_BACKGROUND_FIELD_LABELS = new Set(['診断名', '病名', '現病歴', '既往歴', '手術術式', '術式', '主訴', '入院目的', '入院の経緯', '氏名', '年齢', '性別']);
    function isAssessmentBackgroundItem(item) {
      if (!item || item.aiSuggested) return false;
      if (item.fieldLabel && ASSESSMENT_BACKGROUND_FIELD_LABELS.has(item.fieldLabel)) return true;
      return /と診断され|と診断を受け|の診断で入院/.test(item.text || '');
    }
    // 【同じ場面のS・Oを横に並べる】利用者からの指摘（患者36）：「S（発言）とO（観察）を分けすぎると、臨床の
    // その場の文脈が途切れる。同じ日時・場面のSとOが横並びになる表示にするとよい」。
    // 同じ場面とみなすのは、発言と観察を分けた2枚（sceneIdが同じ）か、日時が時刻まで同じカード。
    // 1つの欄の中のカードを場面ごとにまとめる（順番は最初に出てきた位置のまま）。場面の分からないカードは1枚ずつ。
    function assessmentSceneKey(item) {
      if (item.sceneId) return `id:${item.sceneId}`;
      return timestampClockPart(item.timestamp) ? `ts:${item.timestamp}` : null;
    }
    function groupItemsByScene(list) {
      const scenes = [];
      const byKey = new Map();
      (list || []).forEach(item => {
        const key = assessmentSceneKey(item);
        if (key && byKey.has(key)) { byKey.get(key).items.push(item); return; }
        const scene = { key, items: [item] };
        if (key) byKey.set(key, scene);
        scenes.push(scene);
      });
      // S・Oの両方がある場面だけを横並びにする（S・Oどちらかだけなら普通に縦に並べる）
      return scenes.map(sc => ({ ...sc, paired: sc.items.some(i => i.type === 's') && sc.items.some(i => i.type === 'o') }));
    }
    // 総合アセスメント表での並び順（日の順番。S-1・O-1の番号もこの順で付ける）
    function assessmentDisplayOrder(list) {
      return groupItemsByDay(list).flatMap(g => g.items);
    }

    function detectAdmissionPhaseSignal(text) {
      const t = (text || '').trim();
      if (!t) return null;
      if (/入院前/.test(t)) return 'preadmission';
      if (/入院|実習|術前|術中|術後|手術当日|手術前日|翌日|日目|検査データ/.test(t)) return 'postadmission';
      return null;
    }

    // ==========================================================================
    // 総合アセスメント表の「入院前」「入院後」欄への初期振り分け
    // ------------------------------------------------------------------------
    // 以前はカードを新規作成した時点では常に「未分類」欄になり、入院前・入院後のどちらに
    // 属するかは利用者が総合アセスメント表の画面で1件ずつ手作業で振り分ける必要があった。
    // 抽出時点で既に分かっている手がかり（行頭のタイムスタンプ・見出しラベルの種類）から
    // 入院前／入院後が明確に読み取れる場合は、最初から該当欄に振り分けておく。
    // 判断できない場合はこれまで通りnullを返し、呼び出し側で「未分類」のままにする
    // （誤って断定するより、利用者が確認・移動できる状態にしておく方が安全なため）。
    //
    // 【追加：admissionPhaseによる最終フォールバック】上記のタイムスタンプ・見出しラベルの
    // いずれからも判断できない場合（明確なマーカーを伴わない普通の文章等）、利用者からの
    // 提案に基づき、抽出処理側で上から順に読み進めながら記憶している「今どの時期を読んで
    // いるか」の状態（groupClinicalPhrasesWithTimestamps内のadmissionPhase。最初は入院前と
    // 仮定し、入院・実習・術前・術中・術後等の見出しを見つけたら入院後に切り替える）を
    // 最後のフォールバックとして使う。これにより、明示的なマーカーの無い行も、記録の中で
    // 実際に読み進めた位置に応じて「未分類」ではなく妥当な前後の欄に自動で振り分けられる。
    function inferAssessmentColumn(fieldLabel, timestamp, admissionPhase) {
      const ts = (timestamp || '').trim();
      // タイムスタンプに明確な手がかりがあれば、見出しラベルより優先する
      // （同じ「既往歴」の内容でも、[10:15]のように入院後の時刻付きで記録されていれば
      // 入院後の経過記録として書かれている可能性が高いため）。
      // 「術中・術後」のように複数の区切りが1つのタイムスタンプにまとまっている場合があるため、
      // 完全一致ではなく部分一致で判定する。
      if (ts.includes('入院前')) return 'preadmission';
      if (ts.includes('入院時') || ts.includes('検査データ') || ts.includes('術前') || ts.includes('術中') || ts.includes('術後')) return 'postadmission';
      if (/^\d{1,2}[:時]\d{2}/.test(ts)) return 'postadmission'; // 「10:15」等、時刻付きの記録
      if (/手術当日|手術前日|翌日|\d{1,2}:\d{2}$/.test(ts)) return 'postadmission'; // 「手術当日 12:00」等
      if (/日目$/.test(ts)) return 'postadmission'; // 「3日目」等
      if (/^(?:\d{1,4}年)?\d{1,2}月\d{1,2}日/.test(ts)) return 'postadmission'; // 日付付きの経過記録
      // タイムスタンプから判断できない場合、見出しラベルの性質から判断できるものだけ振り分ける
      // （現病歴・既往歴・生活歴は入院までの経過・既往・普段の生活を記す入院前の情報、
      // 　治療方針・治療内容は入院後に行う医療行為の情報）。
      // 氏名・年齢・診断名・手術術式・感染症は、実習記録の冒頭にまとめて書かれる
      // 「受け持ち前の引継ぎ情報」（入院・手術より前の時点で、受け持ちを始めるにあたって
      // 申し送られる基本情報）であるため、既往歴等と同様に入院前として振り分ける。
      if (fieldLabel === '現病歴' || fieldLabel === '既往歴' || fieldLabel === '生活歴'
        || fieldLabel === '氏名' || fieldLabel === '年齢' || fieldLabel === '性別' || fieldLabel === '診断名'
        || fieldLabel === '手術術式' || fieldLabel === '感染症') return 'preadmission';
      if (fieldLabel === '治療方針' || fieldLabel === '治療内容') return 'postadmission';
      if (admissionPhase === 'postadmission' || admissionPhase === 'preadmission') return admissionPhase;
      return null;
    }

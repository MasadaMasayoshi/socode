    (window.APP_FILE_VERSIONS = window.APP_FILE_VERSIONS || {})['03'] = '2026-09-30.6'; // 版（scripts/stamp-version.js が書き込む）
    // ==========================================================================
    // 検査値カードの抽出：値のすぐ後（スペースの有無を問わず）に単位まで書かれている場合、
    // 値と単位が別々のカードに分かれてしまう不具合の対策。
    // ------------------------------------------------------------------------
    // 以前は「WBC\s*\d+[\d,]*」のように数値までしか正規表現がマッチしなかったため、
    // 記録に「WBC 11200/μL」のように単位まで直接書かれていると、単位部分（"/μL"）が
    // 数値側の抽出から漏れて別の断片として残り、"不自然な始まり"の除外条件（助詞等）にも
    // 該当しないため、捨てられずにそのまま別カードとして生成されてしまっていた。
    // ここでは各項目の正規表現に、LAB_STANDARDSに登録済みの単位を「あれば続けて拾う」
    // 形でoptionalに含めることで、単位が書かれていてもいなくても値と同じカードにまとまる
    // ようにする。単位が書かれているかどうかに関わらず、formatLabValueStringが自動で
    // 単位・基準値を補う（単位が既に書かれている場合も基準値だけは追記する。利用者からの
    // 報告：単位だけ書かれていて基準値が付いていない検査値カードがあった）。
    // ==========================================================================
    function escapeRegExp(str) { return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

    // 元のlabRegexにあった項目と並び順をそのまま踏襲（Hb/HbA1cのように前方一致しうる項目は
    // より長いキーを先に置く）。Clのみ、LAB_STANDARDSには定義済みだったが元の正規表現に
    // 含まれておらず単独では抽出できていなかったため、電解質の並び(Na/K/Cl)にあわせて追加する。
    const LAB_KEY_NUM_PATTERNS = [
      ['WBC', '\\d+[\\d,]*'], ['CRP', '\\d+\\.?\\d*'], ['HbA1c', '\\d+\\.?\\d*'], ['Hb', '\\d+\\.?\\d*'],
      ['RBC', '\\d+[\\d,]*'], ['Plt', '\\d+[\\d,]*'], ['BUN', '\\d+\\.?\\d*'], ['Cre', '\\d+\\.?\\d*'],
      ['Na', '\\d+'], ['K', '\\d+\\.?\\d*'], ['Cl', '\\d+'], ['AST', '\\d+'], ['ALT', '\\d+'],
      // 「Cr」（クレアチニン。LAB_STANDARDSの説明を参照）
      ['Cr', '\\d+\\.?\\d*'],
      ['Dダイマー', '\\d+\\.?\\d*'], ['BNP', '\\d+\\.?\\d*'], ['PT-INR', '\\d+\\.?\\d*'],
      // TP・Alb・γGTPを追加（LAB_STANDARDSの説明を参照）。「TP」は前方一致で他のキーと
      // 競合しないため並び順を問わないが、他の項目とまとめて分かりやすい位置に置く。
      ['TP', '\\d+\\.?\\d*'], ['Alb', '\\d+\\.?\\d*'], ['γGTP', '\\d+\\.?\\d*'],
      // Ht・PTを追加（LAB_STANDARDSの説明を参照）
      ['Ht', '\\d+\\.?\\d*'], ['PT', '\\d+\\.?\\d*'],
      // ALP・T-Bil・血糖・アミラーゼを追加（LAB_STANDARDSの説明を参照）。「T-Bil」は
      // 「-」を含むためescapeRegExpで正しくエスケープされる。
      ['ALP', '\\d+\\.?\\d*'], ['T-Bil', '\\d+\\.?\\d*'], ['血糖', '\\d+\\.?\\d*'], ['アミラーゼ', '\\d+\\.?\\d*']
    ];
    // 【単位と小数】利用者からの報告：「Plt 28.7万/uL」が「Plt 28」と「.7万/uL」の2枚に分かれ、「CRP 1 mg/L」が
    // 換算されずに「CRP 1 mg/dL」になっていた。以前は WBC・RBC・Plt の数値を整数としてしか読まず、単位もアプリの
    // 標準の単位（CRPなら mg/dL）しか読まなかったため。数値はどの項目も小数・カンマ付きで読み、単位は
    // よく使われる単位の一覧（LAB_UNIT_WORDS）から実際に書かれたものを読む（換算は js/07 の formatLabValueString）。
    // カンマは数字の間だけ（「WBC 11200, CRP 3.8」の区切りのカンマを数値に含めない）
    const LAB_NUMBER_SOURCE = '\\d(?:[\\d,]*\\d)?(?:\\.\\d+)?';
    const LAB_UNIT_WORDS = ['mL/min/1.73m2', 'mL/分/1.73m2', '×10^6/μL', '×10^4/μL', '×10^3/μL', '×10^2/μL', '×10^4/uL', '×10^3/uL', 'x10^4/μL', 'x10^3/μL',
      '×10⁴/μL', '×10³/μL', '万/μL', '万/uL', '万/µL', '万/mm3', '万/mm³', '千/μL', '千/uL', '/μL', '/uL', '/µL', '/mm3', '/mm³',
      'μg/mL', 'ug/mL', 'µg/mL', 'μg/dL', 'ng/mL', 'pg/mL', 'mg/dL', 'mg/L', 'g/dL', 'g/L', 'mEq/L', 'mmol/L', 'μmol/L', 'umol/L', 'µmol/L',
      'IU/L', 'U/L', 'fL', '%', '秒', '万', '/mL',
      // OCR（写真の文字起こし）でよくある読み違い（μ→从・u、mEq→mEa）
      '万/从L', '/从L', '万u/L', '万μ/L', 'mEa/L'];
    const LAB_UNIT_SOURCE = LAB_UNIT_WORDS.slice().sort((a, b) => b.length - a.length)
      .map(u => escapeRegExp(u).replace(/\\\^/g, '\\s*\\^?\\s*').replace(/\//g, '\\s*\\/\\s*')).join('|');
    const LAB_REGEX_SOURCE = LAB_KEY_NUM_PATTERNS.map(([key]) => {
      const numPattern = LAB_NUMBER_SOURCE;
      const unitSuffix = `(?:\\s*(?:${LAB_UNIT_SOURCE}))?`;
      // 英字の項目名（Na・K・Cl等）の直前がカタカナ・英字の場合は、「セファゾリンNa 1g」「ヘパリンNa」の
      // ような薬の名前（ナトリウム塩）の一部であり、検査値ではない（利用者からのアップロード文書で発覚：
      // 「セファゾリンNa 1g」が「Na 1 mEq/L」という検査値のカードにされていた）。「血清Na 140」のように
      // 漢字が前にある場合は検査値のままとする。
      const guard = /^[A-Za-z]/.test(key) ? '(?<![A-Za-zァ-ヶー])' : '';
      return `${guard}${escapeRegExp(key)}\\s*${numPattern}${unitSuffix}`;
    }).concat([
      // 体温・血圧・SpO2はLAB_STANDARDSに無いバイタルサインのため、単位はこれまで通り直接指定する
      // 単位は「℃」（U+2103の1文字）だけでなく、OCRや他システムからの貼り付けで多い
      // 「°C」（度記号＋C、2文字）の表記も同じ値の一部として続けて拾えるようにする。
      // 「体温 37.0度」の「度」も単位として一緒に拾う（拾わないと「度 血圧125/70」のように
      // 次のカードの先頭に「度」だけが残っていた。利用者からのアップロード文書で発覚）。
      '体温\\s*\\d{2}(?:\\.\\d)?\\s*(?:℃|°C|°c|度)?(?:\\s*[(（](?:腋窩|腋下|口腔|鼓膜|直腸|耳)[)）])?',
      '血圧\\s*\\d{2,3}\\/\\d{2,3}(?:\\s*mmHg)?(?![\\d])',
      'SpO2\\s*\\d{2,3}\\s*%?(?:\\s*[\\(（][^)）]{0,20}[\\)）])?',
      // 脈拍・呼吸数も体温・血圧・SpO2と同様によく使われるバイタルサインだが、これまで専用の
      // 抽出パターンが無く、値と項目名が同じカードにまとまらず「(バイタルサイン)、脈拍72回/分、
      // 呼吸数18回/分、」のように前後の見出し語も含めて1つの雑多なカードに残ってしまっていた。
      // 「脈拍 74回/分 整」のリズム（整・不整）も同じ所見として拾う（残ると次のカードの先頭に「整」だけが付いていた）
      // 「脈拍98回/分、不整あり」のように読点の後の「不整あり」も脈拍と同じ所見として拾う（心不全の事例）
      '脈拍\\s*\\d{2,3}\\s*回\\s*\\/\\s*分(?:\\s*[(（]?(?:整|不整)(?:あり|なし)?[)）]?|[、,]\\s*不整(?:あり|なし)?)?',
      '呼吸数?\\s*\\d{1,3}\\s*回\\s*\\/\\s*分',
      // 電子カルテ風の略語（BP・P・R・T）も同じバイタルとして拾う（産褥の事例で「BP 112/68mmHg」がタグ未設定だった）
      '(?<![A-Za-z])BP\\s*\\d{2,3}\\/\\d{2,3}\\s*(?:mmHg)?',
      '(?<![A-Za-z])P\\s*\\d{2,3}\\s*回\\s*\\/\\s*分',
      '(?<![A-Za-z])R\\s*\\d{1,2}\\s*回\\s*\\/\\s*分',
      '(?<![A-Za-z])T\\s*\\d{2}(?:\\.\\d)?\\s*(?:℃|°C|°c|度)',
      // BT・HR・PR・RR（単位を書かないことも多い。COPDの事例で「BT 37.8℃ HR 108 RR 26」が1つの体温のカードになっていた）
      '(?<![A-Za-z])BT\\s*\\d{2}(?:\\.\\d)?\\s*(?:℃|°C|°c|度)?',
      '(?<![A-Za-z])(?:HR|PR)\\s*\\d{2,3}(?:\\s*回\\s*\\/\\s*分|\\s*bpm)?(?![\\d.])',
      '(?<![A-Za-z])RR\\s*\\d{1,2}(?:\\s*回\\s*\\/\\s*分)?(?![\\d.])'
    ]).join('|');
    // AI抽出結果など、chunk.isLabOrVitalのようなフラグを持たない文章に対して「検査値・バイタルサインらしさ」を
    // 判定するための正規表現（食事タグの自動付与などに使う。LAB_REGEX_SOURCE自体は抽出用に前後一致を厳密には
    // 求めていないため、ここでは文章中に含まれているかどうかの簡易判定として流用する）。
    const LAB_VALUE_TEST_REGEX = new RegExp(LAB_REGEX_SOURCE, 'i');
    // 「各検査項目は食事タグを付与」：LAB_VALUE_TEST_REGEXは項目名の直後に数値が続く場合しか
    // 一致しないため、「WBCが上昇傾向」のように数値を伴わず項目名だけが文章中に出てくる場合は
    // 対象外だった。項目名（LAB_KEY_NUM_PATTERNSのキー）が単語として含まれているかどうかだけを
    // 見る、より広い判定をタグ付与専用に用意する（\bで区切ることで、日本語文中でも英字項目名
    // の前後だけを正しく境界として認識できる）。
    // 「K」のような1文字のキーは、数値を伴わない場合「Kさん」等の人物のイニシャルとも
    // 一致してしまい誤タグ付けのおそれがある。以前はこれを避けるため1文字キーを丸ごと
    // 判定対象から除外していたが、それでは「Kが低下」「K 4.2」のような正当な検査値の
    // 言及まで見逃してしまう（ユーザー指摘：「KやNなどの文字は文章の前後をみて値か
    // イニシャルかどうかを判断してください」）。そこで除外は行わず、直後に人名の敬称
    // （さん・様・氏・君・ちゃん）が続く場合だけを「イニシャル（人物名）」とみなして
    // 除外する、前後の文脈に基づく判定に変更する。
    // 【追加修正】上記の\b（単語境界）は、JSの正規表現では[A-Za-z0-9_]のみを「単語文字」として
    // 認識するため、"血糖"や"アミラーゼ"のように全角の日本語だけで構成されたキーには、
    // 前後が常に他の日本語文字であるかどうかにかかわらず、そもそも\bが一致する位置自体が
    // 存在しない（＝\bで挟んだ時点で永久に一致しなくなる）。利用者からの報告で、検査値カード
    // 「血糖 89 mg/dL (基準値: 70〜109 mg/dL)」にタグ2(食事)が付与されないまま「タグ未設定」
    // として残っていたのはこれが原因。ASCII文字（英数字・ハイフン）だけで構成されるキー
    // （K・Na・PT等、人名イニシャルとの誤判定を避ける必要がある）と、日本語のみで構成される
    // キー（血糖・アミラーゼ等、人名との混同リスクが無く\bも意味を持たない）を分けて、
    // 日本語キーの方は\bを付けずに素直な部分一致で判定する。
    //
    // 【追加修正2】ASCIIキー側の末尾の\bにも別の抜けがあった。表や検査結果を貼り付けた際、
    // 項目名と数値の間に空白が無く直接くっついている場合（利用者からの報告事例：
    // 「RBC4587」「Hb12.2g/dl」「Ht37.2%」「Plt23」「AST2」「ALT250U/L」「Na140mEq/L」
    // 「K4.2mEq/L」）、末尾の\bは「文字→数字」の間には成立しない（数字も\bの言う「単語文字」
    // であり、境界にならないため）ため一致できず、これらのカードもタグ未設定のまま残っていた。
    // 末尾の\bを、直後に英字が続く場合だけを除外する否定先読みに置き換えることで、
    // 「項目名の直後に数字が続く」表記も検査値として認識できるようにする（「Kg」のように
    // 直後に英字が続く場合は従来通り除外され、「Na」が「NaOH」等の一部として誤って一致する
    // ことはない）。
    const LAB_KEY_HAS_NON_ASCII_RE = /[^A-Za-z0-9\-]/;
    const LAB_ITEM_ASCII_KEYS = LAB_KEY_NUM_PATTERNS.filter(([k]) => !LAB_KEY_HAS_NON_ASCII_RE.test(k)).map(([k]) => k);
    const LAB_ITEM_NON_ASCII_KEYS = LAB_KEY_NUM_PATTERNS.filter(([k]) => LAB_KEY_HAS_NON_ASCII_RE.test(k)).map(([k]) => k);
    const LAB_ITEM_NAME_REGEX = new RegExp(
      // 直前がカタカナ（「セファゾリンNa」等の薬の名前）の場合、直後が「とともに」「による」「訓練」等の
      // 場合（「PTとともに訓練」＝理学療法士）は検査項目として扱わない（利用者からのアップロード文書で発覚）。
      '(?:(?<![ァ-ヶー])\\b(?:' + LAB_ITEM_ASCII_KEYS.map(escapeRegExp).join('|') + ')(?![A-Za-z])(?!\\s*(?:さん|様|氏|君|ちゃん|とともに|と一緒|による|の介入|の訓練|の指導|の計画|の説明|の評価|の方針|訓練|室|より|から|が|介入|実施|と共に|見守り|[)）、,]|[:：]\\s*(?![\\d.])))' +
      (LAB_ITEM_NON_ASCII_KEYS.length ? '|(?:' + LAB_ITEM_NON_ASCII_KEYS.map(escapeRegExp).join('|') + ')' : '') + ')', 'i'
    );

    // 検査値・バイタルサインのカードに自動で付けるヘンダーソンタグを、その検査が何を見る指標かで決める。
    // 【修正】以前は検査値・バイタルサインであれば一律に2(食事)を付けていたため、腎機能（Cre・BUN・eGFR）、
    // 炎症（WBC・CRP）、凝固・線溶（PT・APTT・Dダイマー）、酸素化（SpO2）までが「食事」に入っていた
    // （利用者からの指摘：「SpO2は酸素化の指標なので1.呼吸」「Cre・BUN・eGFRは3.排泄」「WBC・CRPや
    // PT%・APTT・Dダイマーは感染や血栓リスクの指標として7.体温や9.環境」）。
    // 下のどの区分にも当たらない検査値（TP・ALB・Hb・RBC・Ht・血糖・HbA1c・肝機能・電解質等の栄養・
    // 代謝の指標）は、従来通り2(食事)とする。
    const LAB_CATEGORY_TAG_RULES = [
      // 「呼吸20回/分」のように「数」を付けない書き方の呼吸数も1（利用者からの指摘：患者36。以前は2.食事になっていた）
      // BNP（心不全の指標）も1（長文の心不全事例のテストで追加）
      { tags: [1], regex: /(SpO2|SpO₂|SPO2|酸素飽和度|PaO2|PaCO2|呼吸数|呼吸\s*\d|血圧|脈拍|心拍|\bBNP\b|NT-proBNP|\bBP\s*\d|(?<![A-Za-z])[PR]\s*\d+\s*回|(?<![A-Za-z])(?:HR|PR|RR)\s*\d)/i },
      { tags: [3], regex: /(\bCre\b|クレアチニン|\bBUN\b|尿素窒素|eGFR|尿酸|尿蛋白|尿糖|尿比重)/i },
      { tags: [7], regex: /(\bWBC\b|白血球|\bCRP\b|C反応性|体温|(?<![A-Za-z])B?T\s*\d{2})/i },
      // 「PT」は凝固検査のほか理学療法士（PT）の略でも使われるため、数値・%・括弧が続く場合だけを検査とみなす
      { tags: [9], regex: /(APTT|PT-INR|PT%|\bPT(?=\s*[\d%(（])|プロトロンビン|Dダイマー|D-ダイマー|\bFDP\b|フィブリノ|\bPLT\b|血小板)/i }
    ];
    function labCategoryTags(text) {
      const tags = [];
      LAB_CATEGORY_TAG_RULES.forEach(rule => { if (rule.regex.test(text)) rule.tags.forEach(t => { if (!tags.includes(t)) tags.push(t); }); });
      return tags.length ? tags : [2];
    }

    // ==========================================================================
    // 【子どもの記録】受け持ちが新生児・乳児・幼児・学童かを、記録の文章から見分ける（実習生の記録のテストで追加）。
    // 子どもは脈拍・呼吸数の目安が大人と違い、検査値の基準値も年齢で違うため、大人の目安で「高い・低い」を
    // 付けたり、大人の基準値を書き足したりしないようにする。家族の年齢（「兄（3歳）」「父（30歳）」）を読まないよう、
    // 受け持ちを示す言葉（患児・受け持ち・患者・〜ちゃん など）のそばの年齢だけを見る。
    // 返す値：'neonate'（新生児）｜'infant'（乳児）｜'toddler'（幼児）｜'school'（学童）｜null（大人・思春期・分からない）
    // ==========================================================================
    function detectAgeGroupFromText(text) {
      const t = String(text || '').normalize('NFKC').slice(0, 1500);
      if (/日齢\s*\d+|修正\s*\d+\s*週|NICU|GCU|早産児|低出生体重児|新生児(?:期|室)?(?:[:：]|\s|を|の受け持ち)/.test(t) && !/(?:褥婦|産褥|初産婦|経産婦)/.test(t.slice(0, 300))) return 'neonate';
      const who = '(?:患児|受け?持ち?児?|患者|対象|本児|利用者|[A-ZＡ-Ｚ]\\s*(?:ちゃん|くん|君|さん|氏))';
      if (new RegExp(`${who}[^。\\n]{0,20}?生後\\s*\\d+\\s*(?:か月|ヶ月|カ月|ケ月)`).test(t)) return 'infant';
      const m = t.match(new RegExp(`${who}[^。\\n]{0,20}?(\\d{1,3})\\s*歳`));
      if (!m) return null;
      const age = Number(m[1]);
      if (age < 1) return 'infant';
      if (age <= 5) return 'toddler';
      if (age <= 12) return 'school';
      return null;
    }
    // 年齢の区分ごとの脈拍・呼吸数の目安（小児看護の教科書の一般的な値。施設で違うことがあるので「目安」と表示する）
    const CHILD_VITAL_GUIDES = {
      neonate: { label: '新生児', pulse: [120, 160], resp: [40, 60] },
      infant: { label: '乳児', pulse: [110, 140], resp: [30, 40] },
      toddler: { label: '幼児', pulse: [90, 120], resp: [20, 30] },
      school: { label: '学童', pulse: [70, 110], resp: [18, 25] }
    };
    // 子どもの記録では、年齢で変わる検査の基準値（白血球・ヘモグロビン・アルブミン・クレアチニンなど）は大人の値を
    // 書き足さない。年齢で大きく変わらないもの（CRP・Na・Cl）だけ書き足す。
    const CHILD_SAFE_LAB_REFERENCE_KEYS = new Set(['CRP', 'Na', 'Cl']);

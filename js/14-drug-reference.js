    // （カードに付けるタグは増やしすぎない。副作用で関係する項目は「薬」の印を押すと分かる）
    function drugTagsForText(text, { primaryOnly = false } = {}) {
      const ids = new Set();
      findDrugsInText(text).forEach(({ drug }) => (primaryOnly ? drug.tags.slice(0, 1) : drug.tags).forEach(t => ids.add(t)));
      return Array.from(ids);
    }

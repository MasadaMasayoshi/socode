    const DRUG_REFERENCE = DRUG_REFERENCE_ROWS.map(([name, brands, cls, use, watch, tags, alert], k) => ({
      id: `drug_${k}`, name, brands: String(brands || '').split('/').map(b => b.trim()).filter(Boolean), cls, use, watch, tags: tags || [], highAlert: !!alert
    }));
    // 記録の中の書き方（全角・半角、「ラシックス錠20mg」「ソリタT3号」など）で見つけるための語。長い語から先に探す
    // （「インスリン アスパルト」の「インスリン」だけに当たらないように）。2文字以下の商品名は誤って当たりやすいので使わない。
    const DRUG_TERM_INDEX = (() => {
      const list = [];
      const norm = s => String(s).normalize('NFKC').replace(/\s+/g, '');
      DRUG_REFERENCE.forEach(d => {
        // 英大文字だけの短い略語（RBC・PC・FFP など）は検査値・ほかの略語と重なるので使わない
        const terms = new Set([d.name, ...d.brands].map(norm).filter(t => t.length >= 3 && !/^[A-Z]{1,3}$/.test(t)));
        // 「ブデソニド・ホルモテロール」のような合剤は、「・」の前の成分名だけでは当てない（単剤と区別できないため）
        terms.forEach(t => list.push({ term: t, drug: d }));
      });
      return list.sort((a, b) => b.term.length - a.term.length);
    })();
    const DRUG_ESCAPED = s => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
    const DRUG_FIND_REGEX = new RegExp(DRUG_TERM_INDEX.map(x => DRUG_ESCAPED(x.term)).join('|'), 'g');
    const DRUG_BY_TERM = new Map(DRUG_TERM_INDEX.map(x => [x.term, x.drug]));
    // 文章の中の薬を見つける（同じ薬は1回だけ）。返す値：[{ drug, term }]
    function findDrugsInText(text) {
      // 空白は除いてから探す（「インスリン グラルギン」「ソリタ T3」のような書き方にも当てる）
      const flat = String(text || '').normalize('NFKC').replace(/\s+/g, '');
      const out = [];
      const seen = new Set();
      DRUG_FIND_REGEX.lastIndex = 0;
      let m;
      while ((m = DRUG_FIND_REGEX.exec(flat)) !== null) {
        const d = DRUG_BY_TERM.get(m[0]);
        if (d && !seen.has(d.id)) { seen.add(d.id); out.push({ drug: d, term: m[0] }); }
      }
      return out;
    }

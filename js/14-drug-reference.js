    // PMDA（医薬品医療機器総合機構）の医療用医薬品の添付文書情報の検索ページ
    function drugLabelSearchUrl(drug) {
      return `https://www.kegg.jp/medicus-bin/search_drug?search_keyword=${encodeURIComponent(drug.name.replace(/（.*?）/g, '').split('・')[0])}`;
    }
